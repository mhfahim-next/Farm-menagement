// Which translation keys the browser needs. Server components translate on the
// server, so only keys used by client code ("use client" files, and the shared
// code in src/components and src/lib they call) are sent with each page.
// Run `npm run i18n:client-keys` after adding text to client code;
// tests/unit/client-keys.test.ts fails while the list is out of date.
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(fileURLToPath(new URL(".", import.meta.url)), "..");
const OUT = join(ROOT, "src/lib/i18n/client-keys.ts");

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    return statSync(p).isDirectory() ? walk(p) : /\.tsx?$/.test(name) ? [p] : [];
  });
}

/** Every key in the English catalog. */
function allKeys() {
  const dir = join(ROOT, "src/lib/i18n/messages/en");
  const keys = new Set();
  for (const f of readdirSync(dir)) for (const m of readFileSync(join(dir, f), "utf8").matchAll(/^\s*"([^"]+)":/gm)) keys.add(m[1]);
  return keys;
}

export function clientKeys() {
  const keys = allKeys();
  const files = walk(join(ROOT, "src")).filter((p) => {
    const rel = relative(ROOT, p).replaceAll("\\", "/");
    if (rel.startsWith("src/lib/i18n/")) return false;
    const src = readFileSync(p, "utf8").trimStart();
    if (src.startsWith('"use client"')) return true;
    // Shared code client components import (not server-only modules).
    return (rel.startsWith("src/components/") || rel.startsWith("src/lib/")) && !src.startsWith('import "server-only"');
  });
  const literal = new Set();
  const prefixes = new Set();
  for (const p of files) {
    const src = readFileSync(p, "utf8");
    for (const m of src.matchAll(/["'`]([a-zA-Z][\w-]*(?:\.[\w-]+)+)["'`]/g)) literal.add(m[1]);
    // Built keys: t(`sales.unitName.${unit}`) needs every "sales.unitName." key.
    for (const m of src.matchAll(/`([a-zA-Z][\w-]*(?:\.[\w-]+)*\.)\$\{/g)) prefixes.add(m[1]);
  }
  // Used by the shared translator itself (enum and category labels).
  for (const p of ["enum.", "cat."]) prefixes.add(p);
  return [...keys].filter((k) => literal.has(k) || [...prefixes].some((p) => k.startsWith(p))).sort();
}

export const render = (keys) =>
  `// Generated by scripts/client-keys.mjs — do not edit. The translation keys client code uses;\n// only these are sent to the browser with each page.\nexport const CLIENT_KEYS: readonly string[] = ${JSON.stringify(keys, null, 2)};\n`;

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(OUT, render(clientKeys()));
  console.log(`client-keys: ${clientKeys().length} keys`);
}
